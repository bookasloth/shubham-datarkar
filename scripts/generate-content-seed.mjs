// Reads the static content arrays and emits INSERT SQL. Does NOT touch the DB.
// Run: npx tsx scripts/generate-content-seed.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import { caseStudies } from "../src/lib/data/case-studies.ts";
import { projects } from "../src/lib/data/projects.ts";
import { products } from "../src/lib/data/products.ts";
import { services } from "../src/lib/data/services.ts";
import { testimonials } from "../src/lib/data/testimonials.ts";

const jsonLiteral = (obj) => `'${JSON.stringify(obj).replace(/'/g, "''")}'::jsonb`;
const slugLiteral = (s) => (s ? `'${String(s).replace(/'/g, "''")}'` : "null");

function block(table, rows, getSlug) {
  const values = rows
    .map((r, i) => `  (${slugLiteral(getSlug(r))}, ${jsonLiteral(r)}, ${i})`)
    .join(",\n");
  return `-- ${table} (${rows.length})
insert into public.${table} (slug, data, sort)
values
${values}
on conflict do nothing;
`;
}

const sql = `-- GENERATED by scripts/generate-content-seed.mjs — do not edit by hand.
-- Seeds content tables from the original static data. Run manually AFTER
-- 20260615000002_create_content.sql has created the tables.

${block("case_studies", caseStudies, (r) => r.slug)}
${block("projects", projects, (r) => r.slug)}
${block("products", products, (r) => r.slug)}
${block("services", services, (r) => r.slug)}
${block("testimonials", testimonials, () => null)}
`;

mkdirSync("supabase/seed", { recursive: true });
writeFileSync("supabase/seed/content_seed.sql", sql);
console.log(
  `Wrote supabase/seed/content_seed.sql — case_studies:${caseStudies.length} projects:${projects.length} products:${products.length} services:${services.length} testimonials:${testimonials.length}`,
);
